function buildDemoCatalog(): CatalogPart[] {
  const generated: CatalogPart[] = [];
  VARIANT_MODELS.forEach((variant, vIdx) => {
    VARIANT_TEMPLATES.forEach((tpl, tIdx) => {
      const lp = variant.lpOffset + (tIdx + 1) * 137 + vIdx * 19;
      const codeNum = String(10000 + vIdx * 1000 + (tIdx + 1) * 17);
      generated.push({
        lp,
        modelWozka: variant.model,
        nrKatalogowy: `${variant.prefix}-${codeNum}`,
        nazwaPl: tpl.nazwaPl,
        nazwaEn: tpl.nazwaEn,
        nazwaCn: tpl.nazwaCn,
        ilosc: tpl.ilosc,
        uwagi: tpl.uwagi,
        stronaPdf: Number(tpl.stronaPdf) + vIdx * 2,
      });
    });
  });

  return [...BASE_PARTS, ...generated].sort((a, b) => Number(a.lp) - Number(b.lp));
}

export const DEMO_CATALOG: CatalogPart[] = buildDemoCatalog();
